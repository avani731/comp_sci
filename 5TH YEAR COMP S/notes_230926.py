#NOT operator
x = 2
if not (x>5):# when the not operator is typed it reverses the info if 
    print('x is less than or equal to 5')
    
#AND operator
x = 2
if(x<5)and(x>1):#and will work when both info are true
    print('x is less than 5 and greater than 1')
    
#OR operator
x = 2
if (x<5)and(x>1):# return true if either operands is true
    print('x is less than 5 or greater than 1')